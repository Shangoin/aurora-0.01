class LeadCreate(BaseModel):
    """Inbound form submission from landing page"""
    name: str = Field(..., min_length=2, max_length=100)
    email: EmailStr
    phone: str | None = None
    company: str | None = None
    lead_volume: str | None = None
    message: str | None = None

    @field_validator("phone")
    @classmethod
    def validate_phone(cls, v: str | None) -> str | None:
        if v:
            cleaned = v.replace(" ", "").replace("-", "").replace("(", "").replace(")", "")
            if len(cleaned) < 7:
                raise ValueError("Phone number too short")
        return v


class LeadScore(BaseModel):
    """AI scoring result: 0-100 score, tier, and ICP reasoning."""
    score: int = Field(..., ge=0, le=100)
    tier: LeadTier
    reasoning: str = ""
    icp_fit: bool = False
    urgency: str = ""
    budget_signals: list[str] = Field(default_factory=list)
    recommended_delay_minutes: int = 60


class LeadResponse(BaseModel):
    """API response returned to the landing page after lead submission."""
    id: str
    status: str
    score: int
    tier: LeadTier
    message: str


