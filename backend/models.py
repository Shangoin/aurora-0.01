class GeoRegion(str, Enum):
    INDIA = "india"
    US = "us"
    UK = "uk"
    GLOBAL = "global"


class CallScores(BaseModel):
    """9-dimensional call performance scores (0-100 each) + weighted overall."""
    opening: int = Field(0, ge=0, le=100)
    discovery: int = Field(0, ge=0, le=100)
    rapport: int = Field(0, ge=0, le=100)
    objection_handling: int = Field(0, ge=0, le=100)
    closing: int = Field(0, ge=0, le=100)
    naturalness: int = Field(0, ge=0, le=100)
    relevance: int = Field(0, ge=0, le=100)
    pacing: int = Field(0, ge=0, le=100)           # Conversation tempo — not rushing or dragging
    silence_handling: int = Field(0, ge=0, le=100) # Uses pauses effectively, not filling every gap
    overall: int = Field(0, ge=0, le=100)          # Weighted composite of all 9 dimensions


class ScriptImprovement(BaseModel):
    """A single script improvement suggestion generated by the critique engine."""
    category: str
    current_behavior: str
    suggested_behavior: str
    example_script: str
    impact: ImprovementImpact


class ProspectAnalysis(BaseModel):
    """Structured intelligence about the prospect extracted from the call transcript."""
    pain_points: list[str] = []
    buying_stage: str = "unknown"   # awareness | consideration | decision | unknown
    sentiment_overall: str = "neutral"   # positive | neutral | negative | hostile
    budget_signals: str = ""
    objections_raised: list[str] = []


class CallCritique(BaseModel):
    """Full 9-category critique result returned by critique_call()."""
    call_id: str
    scores: CallScores
    overall_score: int
    one_line_summary: str
    meeting_booked: bool = False
    should_follow_up: bool = True
    follow_up_strategy: str = ""   # email | call | whatsapp | sms | none
    estimated_deal_probability: int = 0
    prospect_analysis: ProspectAnalysis = Field(default_factory=ProspectAnalysis)
    action_items: list[str] = []
    script_improvements: list[ScriptImprovement] = []
    coach_verdict: str = ""


class VapiWebhookPayload(BaseModel):
    """Inbound Vapi webhook event — extra fields allowed (Vapi schema evolves)."""
    model_config = ConfigDict(extra="allow")

    message: dict | None = None
    call: dict | None = None


