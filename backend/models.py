class PatternAnalysis(BaseModel):
    """A recurring failure pattern identified during MARS meta-analysis."""
    issue: str
    frequency: int
    impact: str
    example_from_calls: str


class PromptUpdate(BaseModel):
    """New Vapi system prompt generated by the MARS improvement cycle."""
    patterns: list[PatternAnalysis]
    updated_system_prompt: str   # complete deployable prompt text (min 500 words)
    changelog: str               # specific measurable changes made
    expected_improvement_areas: list[str]


class PromptModule(BaseModel):
    """Modular prompt section targeted by MCTS for diff-based editing."""
    module_name: str          # 'opening' | 'discovery' | 'objection' | 'closing' | 'persona'
    content: str              # The actual prompt text for this module
    version: int = 1
    score_delta: float = 0.0  # Measured improvement since last version


class MCTSNode(BaseModel):
    """Budget-aware MCTS planning node for the MARS improvement loop."""
    module: str               # Which prompt module this node targets
    proposed_change: str      # Human-readable description of the change
    expected_score_delta: float  # Expected improvement (0–20 typical)
    estimated_tokens: int     # Compute cost estimate
    mcts_reward: float = 0.0  # score_delta / (tokens / 1000) — higher = more efficient
    depth: int = 0


class MARSLesson(BaseModel):
    """A lesson extracted from a call batch and stored in the mars_lessons table."""
    lesson_type: str          # 'pattern' | 'objection' | 'opening' | 'insight' | 'geo'
    content: str              # The lesson text
    source_calls: int = 1     # How many calls contributed to this lesson
    avg_score_delta: float = 0.0  # Score improvement observed after applying
    mcts_reward: float = 0.0
    geo_region: str | None = None  # Geo-specific lesson if applicable


